#ifndef _WEATHER_VOICE_H
#define _WEATHER_VOICE_H

#include "main.h"

/* ======================== 天气播报 ========================
 * 播报当前城市的天气状况，按顺序播报：
 * 城市名 -> 天气状况 -> 温度 -> 湿度
 * @param weather_file 天气状况对应的音频文件号（03目录下）
 * @param temp         当前温度值（摄氏度）
 * @param hum          当前湿度值（百分比）
 * @param city_file    城市名对应音频文件号（02目录下）
 *==================================================================*/
void Weather_Voice_Play(u8 weather_file, int temp, u16 hum, u8 city_file);

/* ======================== 时间播报 ========================
 * 播报当前 RTC 时间：XXXX年X月X号X点X分
 * 使用文件夹00中的音频文件：
 * 015年, 016月, 017号, 020点, 021分
 * 年份按位一位播报（如2026→二零二六）
 * 月/日/时/分使用 MY1680_PlayNum() 全职称播报
 *==================================================================*/
void Voice_ReportTime(void);

/* ======================== 室内温度播报 ========================
 * 读取 indoor_data.temp 并播报：室内温度 + 数值 + 度
 * 使用00目录下的音频文件：012室内温度, 011度
 *==================================================================*/
void Voice_ReportIndoorTemp(void);

/* ======================== 室内湿度播报 ========================
 * 读取 indoor_data.humi 并播报：室内湿度 + 数值 + 百分之
 * 使用00目录下的音频文件：013室内湿度, 023百分之
 *==================================================================*/
void Voice_ReportIndoorHum(void);

#endif
