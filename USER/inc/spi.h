/*
 * Spi1_Config - SPI1外设初始化配置
 * 功能: 配置SPI1为主机模式，设置数据帧格式（8位或16位）、
 *       时钟极性（CPOL）、时钟相位（CPHA）、波特率分频系数、
 *       数据顺序（MSB/LSB优先）等参数
 * 参数: 无
 * 返回值: 无
 * 说明: 该函数同时需要配置SPI1相关的GPIO引脚（SCK、MISO、MOSI、CS）
 *       为复用功能推挽输出/浮空输入模式
 */
void Spi1_Config(void);

/*
 * Spi1_TransferData - SPI1数据收发（全双工）
 * 功能: 通过SPI1总线发送一个字节数据，并同时接收从设备返回的一个字节数据
 * 参数: data - 要发送的数据字节
 * 返回值: u8 - 从SPI从设备接收到的数据字节
 * 说明: SPI是全双工通信，发送和接收同时进行；
 *       该函数会阻塞等待传输完成；
 *       如果需要接收数据但无需发送，可发送0x00或0xFF
 */
u8 Spi1_TransferData(u8 data);

